-- Create USERS table
CREATE TABLE users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) UNIQUE NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    role VARCHAR2(20) NOT NULL CHECK (role IN ('admin','librarian','student')),
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(100),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- Create BOOKS table
CREATE TABLE books (
    book_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(200) NOT NULL,
    author VARCHAR2(100) NOT NULL,
    isbn VARCHAR2(20) UNIQUE,
    total_copies NUMBER DEFAULT 1,
    available_copies NUMBER DEFAULT 1,
    category VARCHAR2(50),
    description CLOB,
    added_date TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- Create ISSUES table
CREATE TABLE issues (
    issue_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    book_id NUMBER NOT NULL,
    issue_date DATE NOT NULL,
    due_date DATE NOT NULL,
    return_date DATE,
    status VARCHAR2(20) DEFAULT 'active' CHECK (status IN ('active','returned','overdue')),
    CONSTRAINT fk_issue_user FOREIGN KEY (user_id) REFERENCES users(user_id),
    CONSTRAINT fk_issue_book FOREIGN KEY (book_id) REFERENCES books(book_id)
);

-- Create FINES table
CREATE TABLE fines (
    fine_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id NUMBER NOT NULL,
    amount NUMBER(10,2) NOT NULL,
    fine_date DATE NOT NULL,
    status VARCHAR2(20) DEFAULT 'pending' CHECK (status IN ('pending','paid')),
    paid_date DATE,
    CONSTRAINT fk_fine_issue FOREIGN KEY (issue_id) REFERENCES issues(issue_id)
);

-- Create LOAN_REQUESTS table (for approval workflow)
CREATE TABLE loan_requests (
    request_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    book_id NUMBER NOT NULL,
    request_date DATE DEFAULT SYSDATE,
    status VARCHAR2(20) DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),
    approved_by NUMBER,
    approved_date DATE,
    due_date DATE,
    notes VARCHAR2(500),
    CONSTRAINT fk_request_user FOREIGN KEY (user_id) REFERENCES users(user_id),
    CONSTRAINT fk_request_book FOREIGN KEY (book_id) REFERENCES books(book_id),
    CONSTRAINT fk_approved_by FOREIGN KEY (approved_by) REFERENCES users(user_id)
);

-- Create indexes for performance
CREATE INDEX idx_issues_user ON issues(user_id);
CREATE INDEX idx_issues_book ON issues(book_id);
CREATE INDEX idx_issues_status ON issues(status);
CREATE INDEX idx_fines_status ON fines(status);
CREATE INDEX idx_loan_req_status ON loan_requests(status);

